CREATE DATABASE IF NOT EXISTS edumentor_php CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE edumentor_php;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 correo VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS recursos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id INT UNSIGNED NOT NULL,
 tipo VARCHAR(30) NOT NULL,
 materia VARCHAR(100) NOT NULL,
 nivel VARCHAR(100) NOT NULL,
 tema VARCHAR(160) NOT NULL,
 resultado LONGTEXT NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS evidencias (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id INT UNSIGNED NOT NULL,
 estrategia VARCHAR(150) NOT NULL,
 tema VARCHAR(150) NOT NULL,
 resultado_antes DECIMAL(5,2) NOT NULL,
 resultado_despues DECIMAL(5,2) NOT NULL,
 observaciones TEXT NOT NULL,
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 CONSTRAINT chk_antes CHECK (resultado_antes BETWEEN 0 AND 100),
 CONSTRAINT chk_despues CHECK (resultado_despues BETWEEN 0 AND 100)
) ENGINE=InnoDB;
